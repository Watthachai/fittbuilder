#!/usr/bin/env node
/**
 * The module screens are real files under `demo/`, because the product renders
 * them as pages. The WebContainer needs the same code as text, so this writes it
 * out once instead of keeping a second hand-maintained copy that drifts.
 *
 * Run `npm run modules:sync` after editing anything under `demo/modules/`.
 * `lib/__tests__/modules-source-sync.test.ts` fails if you forget.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = join(ROOT, "demo/modules");
const OUT = join(ROOT, "lib/modules/generated/sources.ts");

/** Every file under demo/modules, keyed by its path relative to that directory. */
export function collectSources() {
  const files = {};
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else files[relative(SRC, full)] = readFileSync(full, "utf8");
    }
  };
  walk(SRC);
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b)));
}

/** Escape only what would end the template literal or start an interpolation. */
const asTemplate = (s) => "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

export function render(files) {
  const body = Object.entries(files)
    .map(([path, content]) => `  ${JSON.stringify(path)}: ${asTemplate(content)},`)
    .join("\n\n");
  return `// Generated by scripts/sync-module-sources.mjs — do not edit.
// Source of truth: demo/modules/**. Run \`npm run modules:sync\` after changing it.

export const MODULE_SOURCES: Record<string, string> = {
${body}
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = collectSources();
  mkdirSync(join(ROOT, "lib/modules/generated"), { recursive: true });
  writeFileSync(OUT, render(files));
  console.log(`wrote ${Object.keys(files).length} files to lib/modules/generated/sources.ts`);
}
